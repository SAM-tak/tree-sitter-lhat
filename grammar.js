// Keep written syntax in the CST. Name resolution, type checking and effects
// belong to lhatls. Hat words and suffixes stay independently highlightable.
const ident = /[_\p{XID_Start}][_\p{XID_Continue}]*/;
const commaSep1 = rule => seq(rule, repeat(seq(',', rule)));
const commaSep = rule => optional(commaSep1(rule));
const kw = ($, word) => seq(alias(word, $.hat_word), $.hat_suffix);
const words = ($, names) => choice(...names.map(word => kw($, word)));
const op = ($, text) => alias(text, $.operator);
const keywordWords = ['let', 'var', 'module', 'import', 'require', 'enum', 'errordef', 'else', 'el', 'elseif', 'elif', 'catch', 'finally', 'if', 'do', 'with', 'for', 'in', 'from', 'to', 'until', 'step', 'repeat', 'while', 'return', 'yield', '_yield', 'break', 'next', 'continue', 'panic', 'when', 'other', 'closed', 'f', 'p', 'def', 'op', 'delegate', 'self', 'error', 'try', 'await', 'box', 'constbox', 'typeof', 'id', 'pack', 'unpack', 'or', 'and', 'is', 'dot', 'cross', 'fits', 'as', 't', 'c', 'public', 'override', 'overload', 'abstract', 'final', 'static'];
keywordWords.push('pre', 'main', 'post', 'first', 'last', 'prolog', 'epilog');

module.exports = grammar({
  name: 'lhat',
  extras: $ => [/\s/, $.line_comment, $.block_comment],
  externals: $ => [$._block_comment, $._call_open, $._optional_call_open, $._index_open, $._optional_index_open, $._line_end, $.string_content, $.interpolated_content],
  conflicts: $ => [
    [$.identifier, $.phase_clause],
    [$.expression_list, $.yield_expression, $.catch_expression],
    [$.expression_list, $.yield_expression],
    [$.for_binding_statement],
    [$.identifier, $.scoped_expression, $.match_expression],
    [$.identifier, $.yield_expression],
    [$.for_binding_statement, $.identifier, $.for_statement, $.match_statement, $.scoped_expression, $.match_expression],
    [$.identifier, $.yield_statement, $.yield_expression],
    [$.for_binding_statement, $.scoped_expression],
    [$.else_clause], [$.catch_clause], [$.match_statement_arm],
    [$.identifier, $.function_type, $.coroutine_type],
    [$.identifier, $.if_statement, $.if_expression],
    [$.identifier, $.function_expression, $.function_type],
    // A bare word is always a user name; with an adjacent hat it may also
    // introduce syntax. Keep both branches until following tokens decide.
    ...['variable_declaration', 'module_declaration', 'enum_declaration',
      'error_declaration', 'modifier', 'else_clause', 'catch_clause', 'finally_clause',
      'do_statement', 'repeat_statement', 'return_statement', 'jump_statement',
      'panic_statement', 'function_expression', 'definition_expression',
      'definition_member', 'delegate_member', 'self_expression', 'error_expression',
      'if_expression', 'table_type', 'instance_type', 'function_type',
      'coroutine_type'].map(name => [$.identifier, $[name]]),
    [$.panic_statement, $.catch_expression],
    [$.expression_list, $.catch_expression],
    [$._type, $.qualified_type],
    [$.expression_statement, $.catch_expression],
    [$.expression_list, $._table_entry],
    [$.expression_statement, $._table_entry],
    [$.block, $.table_expression],
    [$.binding, $._expression],
    [$._path, $._expression],
    [$.import_statement, $._expression],
    [$._expression, $.table_field],
    [$.parameter, $._type],
  ],
  rules: {
    source_file: $ => repeat($._statement),
    _statement: $ => choice(
      $.variable_declaration, $.module_declaration, $.import_statement,
      $.enum_declaration, $.error_declaration, $.assignment_statement,
      $.if_statement, $.for_statement, $.repeat_statement, $.do_statement,
      $.match_statement, $.return_statement, $.yield_statement, $.jump_statement,
      $.panic_statement, $.expression_statement, $.empty_statement, $.for_binding_statement, $.phase_clause,
    ),
    empty_statement: _ => ';',
    phase_clause: $ => seq(words($, ['pre', 'main', 'post', 'first', 'last', 'prolog', 'epilog']), ':'),
    for_binding_statement: $ => seq(kw($, 'for'), $.variable_declaration, optional(seq(words($, ['until', 'while']), $._expression, optional(seq(kw($, 'next'), $.assignment_statement)), $.block))),
    _name: $ => choice($.identifier, $.name_literal, $.hat_identifier, $.scoped_identifier),
    identifier: _ => choice(ident, ...keywordWords),
    hat_suffix: _ => token.immediate(/\^+/),
    hat_identifier: $ => prec(1, seq(alias($.identifier, $.hat_word), $.hat_suffix)),
    scoped_identifier: $ => seq($.scoped_name, optional($.hat_suffix)),
    scoped_name: _ => token(seq(/\$[\$\^]*/, ident)),
    name_literal: _ => token(seq('`', repeat1(choice('``', /[^`\r\n]/)), '`')),
    annotation: $ => seq(token(seq('@', ident)), optional($.arguments)),
    modifier: $ => words($, ['public', 'override', 'overload', 'abstract', 'final', 'static']),
    variable_declaration: $ => seq(
      repeat(choice($.annotation, $.modifier)),
      field('kind', words($, ['let', 'var'])),
      field('bindings', commaSep1($.binding)), '=', field('value', $.expression_list),
    ),
    binding: $ => seq(field('name', $._name), optional($.type_annotation)),
    type_annotation: $ => seq(':', field('type', $._type)),
    module_declaration: $ => seq(kw($, 'module'), field('name', $._path)),
    _path: $ => seq($._name, repeat(seq('.', $._name))),
    import_statement: $ => seq(words($, ['import', 'require']), field('module', choice($.string, $.raw_string, $._path))),
    enum_declaration: $ => seq(repeat(choice($.annotation, $.modifier)), kw($, 'enum'), field('name', $._name), '{', commaSep($.enum_member), optional(','), '}'),
    enum_member: $ => seq(field('name', $._name), optional(seq('=', field('value', $._expression)))),
    error_declaration: $ => seq(repeat(choice($.annotation, $.modifier)), kw($, 'errordef'), field('name', $._name), '{', commaSep($.error_member), optional(','), '}'),
    error_member: $ => seq(field('name', $._name), optional($.field_block)),
    assignment_statement: $ => seq(field('left', $.expression_list), field('operator', $.assignment_operator), field('right', $.expression_list)),
    assignment_operator: _ => choice(':=', '+=', '-=', '*=', '/=', '%=', '//=', '**=', '..=', '?:=', '?+=', '?-=', '?*=', '?/=', '?%=', '?//=', '?**=', '?..='),
    expression_statement: $ => $._expression,
    expression_list: $ => commaSep1($._expression),
    block: $ => seq('{', repeat($._statement), repeat($.else_clause), repeat($.catch_clause), optional($.finally_clause), '}'),
    else_clause: $ => seq(words($, ['else', 'el', 'elseif', 'elif']), optional(field('condition', $._expression)), ':', repeat($._statement)),
    catch_clause: $ => seq(kw($, 'catch'), optional(field('pattern', $._expression)), ':', repeat($._statement)),
    finally_clause: $ => seq(kw($, 'finally'), ':', repeat($._statement)),
    if_statement: $ => seq(kw($, 'if'), field('condition', $._expression), field('body', $.block)),
    do_statement: $ => seq(words($, ['do', 'with']), optional(field('value', $._expression)), field('body', $.block)),
    for_statement: $ => seq(kw($, 'for'), field('bindings', commaSep1($.binding)), field('iterator', choice(
      seq(kw($, 'in'), $._expression),
      seq(kw($, 'from'), $._expression, words($, ['to', 'until']), $._expression, optional(seq(kw($, 'step'), $._expression))),
    )), field('body', $.block)),
    repeat_statement: $ => seq(kw($, 'repeat'), optional(choice(
      seq(words($, ['while', 'until']), $._expression), $._expression,
    )), field('body', $.block)),
    return_statement: $ => seq(kw($, 'return'), choice($._line_end, $.expression_list)),
    yield_statement: $ => seq(words($, ['yield', '_yield']), choice($._line_end, $.expression_list)),
    jump_statement: $ => words($, ['break', 'next', 'continue']),
    panic_statement: $ => seq(kw($, 'panic'), $._expression),
    match_statement: $ => seq(kw($, 'for'), field('value', $._expression), '{', repeat1($.match_statement_arm), optional($.match_statement_default), '}'),
    match_statement_arm: $ => seq(kw($, 'when'), field('pattern', $.expression_list), ':', repeat($._statement)),
    match_statement_default: $ => seq(kw($, 'other'), ':', repeat($._statement)),

    _expression: $ => choice(
      $._name, $.number, $.string, $.raw_string, $.line_string, $.interpolated_string,
      $.table_expression, $.function_expression, $.definition_expression, $.self_expression,
      $.error_expression, $.parenthesized_expression, $.call_expression, $.member_expression,
      $.index_expression, $.unary_expression, $.binary_expression, $.type_test_expression,
      $.presence_expression, $.spread_expression, $.varargs, $.if_expression, $.match_expression,
      $.catch_expression, $.prefix_expression, $.table_type, $.coroutine_type, $.function_type,
      $.yield_expression, $.scoped_expression,
    ),
    yield_expression: $ => prec.right(seq(words($, ['yield', '_yield']), $._expression)),
    scoped_expression: $ => seq(repeat1(seq(kw($, 'for'), $.variable_declaration)), kw($, 'do'), ':', $.expression_list, ';'),
    number: _ => token(choice(
      /0[xX][0-9a-fA-F_]+/, /0[bB][01_]+/, /0[oO][0-7_]+/,
      /[0-9][0-9_]*\.[0-9][0-9_]*([eE][+-]?[0-9]+)?/,
      /[0-9][0-9_]*[eE][+-]?[0-9]+/, /[0-9][0-9_]*/,
    )),
    varargs: _ => '...',
    parenthesized_expression: $ => seq('(', $.expression_list, ')'),
    table_expression: $ => seq('{', commaSep($._table_entry), optional(','), '}'),
    _table_entry: $ => choice($.table_field, $.computed_field, $._expression),
    table_field: $ => seq(field('name', $._name), choice('=', ':='), field('value', $._expression)),
    computed_field: $ => seq('[', field('key', $._expression), ']', choice('=', ':='), field('value', $._expression)),
    function_expression: $ => seq(optional(kw($, 'closed')), field('kind', words($, ['f', 'p'])), optional($.parameters), optional($.return_type), field('body', $.block)),
    parameters: $ => commaSep1($.parameter),
    parameter: $ => seq(field('name', choice($._name, $.qualified_type, $.table_type, $.coroutine_type, $.varargs)), optional($.type_annotation)),
    return_type: $ => seq('->', $._type),
    definition_expression: $ => seq(kw($, 'def'), field('body', $.definition_body)),
    definition_body: $ => seq('{', commaSep(choice($.definition_member, $.self_expression, $.delegate_member)), optional(','), '}'),
    definition_member: $ => seq(repeat(choice($.annotation, $.modifier)), optional(kw($, 'op')), field('name', choice($._name, $.operator_name)), optional($.type_annotation), optional(seq(choice('=', ':='), field('value', $._expression)))),
    operator_name: _ => choice('+', '-', '*', '/', '//', '%', '**', '..', '<=>', '=', 'dot^', 'cross^'),
    delegate_member: $ => seq(kw($, 'delegate'), $._expression),
    self_expression: $ => seq(kw($, 'self'), $.field_block),
    field_block: $ => seq('{', commaSep($.definition_member), optional(','), '}'),
    error_expression: $ => seq(kw($, 'error'), field('kind', $._path), field('fields', $.table_expression)),
    call_expression: $ => prec.left(20, seq(field('function', $._expression), field('arguments', $.arguments))),
    arguments: $ => seq(choice(alias($._call_open, '('), alias($._optional_call_open, '?(')), commaSep($._expression), ')'),
    index_expression: $ => prec.left(20, seq(field('object', $._expression), choice(alias($._index_open, '['), alias($._optional_index_open, '?[')), field('index', $._expression), ']')),
    member_expression: $ => prec.left(20, seq(field('object', $._expression), choice('.', '?.'), field('member', choice($._name, alias(token(prec(2, /[0-9][0-9_]*/)), $.number))))),
    presence_expression: $ => prec.left(20, seq($._expression, '?')),
    spread_expression: $ => prec.left(20, seq($._expression, '...')),
    unary_expression: $ => prec(15, seq(field('operator', op($, choice('-', '+', '!'))), field('operand', $._expression))),
    prefix_expression: $ => prec.right(14, seq(field('operator', words($, ['try', 'await', 'box', 'constbox', 'typeof', 'id', 'import', 'require', 'pack', 'unpack'])), field('operand', $._expression))),
    binary_expression: $ => choice(...[
      [1, ['or']], [2, ['and']], [3, ['is']],
      [3, ['=', '≠', '!=', '=/', '<', '>', '<=', '>=', '≦', '≤', '≧', '≥']],
      [4, ['??']], [5, ['|']], [6, ['&']], [7, ['..']],
      [8, ['+', '-']], [9, ['*', '/', '//', '%']], [9, ['dot', 'cross']],
      [10, ['**']], [3, ['<=>']],
    ].map(([precedence, ops]) => (precedence === 10 ? prec.right : prec.left)(precedence, seq(
      field('left', $._expression), field('operator', choice(...ops.map(text => /^[a-z]+$/.test(text) ? kw($, text) : op($, text)))), field('right', $._expression),
    )))),
    type_test_expression: $ => prec.left(3, seq($._expression, words($, ['fits', 'as']), $._type)),
    catch_expression: $ => prec.right(0, seq($._expression, kw($, 'catch'), choice($._expression, $.panic_statement))),
    if_expression: $ => seq(kw($, 'if'), field('condition', $._expression), ':', field('consequence', $._expression), repeat($.conditional_alternative), words($, ['else', 'el']), ':', field('alternative', $._expression), ';'),
    conditional_alternative: $ => seq(words($, ['elseif', 'elif']), $._expression, ':', $._expression),
    match_expression: $ => seq(kw($, 'for'), field('value', $._expression), ':', repeat1($.match_expression_arm), optional($.match_expression_default), ';'),
    match_expression_arm: $ => seq(kw($, 'when'), field('pattern', $._expression), ':', field('value', $._expression)),
    match_expression_default: $ => seq(kw($, 'other'), ':', $._expression),

    _type: $ => choice($._name, $.qualified_type, $.table_type, $.coroutine_type, $.function_type, $.generic_type, $.tuple_type, $.union_type, $.intersection_type, $.array_type),
    qualified_type: $ => prec.left(seq($._name, repeat1(seq('.', $._name)))),
    generic_type: $ => prec(2, seq(choice($._name, $.qualified_type), '<', commaSep1($._type), '>')),
    tuple_type: $ => seq('(', commaSep1($._type), ')'),
    union_type: $ => prec.left(1, seq($._type, '|', $._type)),
    intersection_type: $ => prec.left(2, seq($._type, '&', $._type)),
    array_type: $ => prec(3, seq($._type, '[', optional($.number), ']')),
    table_type: $ => seq(kw($, 't'), '{', commaSep(choice($.type_member, $.index_signature, $.instance_type, $._type)), optional(','), '}'),
    type_member: $ => seq(field('name', $._name), ':', field('type', $._type)),
    index_signature: $ => seq('[', $._type, ']', ':', $._type),
    instance_type: $ => seq(kw($, 'self'), '{', commaSep(choice($.type_member, $.index_signature, $._type)), optional(','), '}'),
    function_type: $ => seq(words($, ['f', 'p']), optional($.parameters), optional($.return_type), ';'),
    coroutine_type: $ => seq(kw($, 'c'), '{', optional(words($, ['f', 'p'])), commaSep($._type), repeat(seq('->', choice(commaSep1($._type), '*'))), '}'),

    string: $ => seq('"', repeat(choice($.string_content, $.escape_sequence)), '"'),
    escape_sequence: _ => token.immediate(seq('\\', choice(/[nrt0\\"]/, /x[0-9a-fA-F]{2}/, /u\{[0-9a-fA-F]+\}/, /\r?\n/))),
    raw_string: _ => token(seq("'", repeat(choice("''", /[^']/)), "'")),
    line_string: _ => token(prec(2, /"""[^\r\n]*/)),
    interpolated_string: $ => seq('$"', repeat(choice($.interpolated_content, $.interpolation_escape, $.escape_sequence, $.interpolation)), '"'),
    interpolation_escape: _ => token.immediate(prec(2, choice('{{', '}}'))),
    interpolation: $ => seq('{', $._expression, optional(seq(':', optional($.format_specifier))), '}'),
    format_specifier: _ => token.immediate(/[^}]+/),
    line_comment: _ => token(seq('#', optional(seq(/[^\[\r\n]/, /[^\r\n]*/)))),
    block_comment: $ => $._block_comment,
  },
});
